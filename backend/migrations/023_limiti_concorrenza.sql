-- 023_limiti_concorrenza.sql
--
-- BUG/SECURITY migration (audit finding RMY-21): two limits that the backend
-- checked with "read, then write" could be broken by requests arriving at the
-- same moment. The database now enforces them itself.
--
-- (The third one in the finding, at most 10 photos per listing, is already
-- enforced by migration 020, live since 2026-11.)
--
-- 1. At most 10 pending requests ('in_attesa') per room.
--    POST /api/conversations (routes/chat.ts) counts the pending requests and
--    then inserts: two students sending at the same moment could both count 9
--    and both get in (11). The trigger below repeats the check after locking
--    the room row, so requests for the SAME room are checked one at a time.
--    Requests for different rooms do not wait for each other.
--    A refused insert raises SQLSTATE RM009; the backend answers it with the
--    same friendly 409 as its own count check.
--    Keep MAX_RICHIESTE in sync with MAX_PENDING_REQUESTS_PER_ROOM
--    (backend/src/routes/chat.ts).
--
-- 2. Unique waitlist position (utenti.posizione).
--    lib/utenti.ts computed MAX(posizione) + 1 and inserted it, so two users
--    created together could get the same position. posizione is an IDENTITY
--    column (checked live 2026-11-18: GENERATED BY DEFAULT, sequence in step
--    with MAX), so the backend now leaves it to the sequence, which never
--    hands out the same number twice. The unique index makes any duplicate
--    impossible from now on (checked live: no duplicates today). The setval
--    first makes sure the sequence is not behind values inserted by hand.
--
-- RUN THIS BEFORE deploying the backend that comes with it.
--
-- Same access model as 014: the function is SECURITY DEFINER and nobody may
-- call it through the public API.
--
-- Safe to run more than once. To undo:
--   DROP TRIGGER IF EXISTS limita_richieste_in_attesa ON public.conversazioni;
--   DROP FUNCTION IF EXISTS public.limita_richieste_in_attesa();
--   DROP INDEX IF EXISTS public.utenti_posizione_uniq;

-- ===================== 1. PENDING REQUESTS PER ROOM =====================

CREATE OR REPLACE FUNCTION public.limita_richieste_in_attesa()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
declare
  -- Most pending requests one room may have (= MAX_PENDING_REQUESTS_PER_ROOM in the backend).
  MAX_RICHIESTE constant integer := 10;
begin
  -- Only a row that becomes pending counts (a new request, or a closed one
  -- put back to 'in_attesa'). Accepting, refusing or cancelling never blocks.
  if new.stato_richiesta <> 'in_attesa'
     or (tg_op = 'UPDATE' and old.stato_richiesta = 'in_attesa') then
    return new;
  end if;

  -- Lock the room: a second request for the same stanza_id waits here until
  -- the first transaction ends, then sees its row in the count below.
  perform 1 from public.stanze where id = new.stanza_id for update;

  if (
    select count(*) from public.conversazioni
    where stanza_id = new.stanza_id
      and stato_richiesta = 'in_attesa'
      and id is distinct from new.id
  ) >= MAX_RICHIESTE then
    raise exception 'A room can have at most % pending requests', MAX_RICHIESTE
      using errcode = 'RM009';
  end if;

  return new; -- BEFORE trigger: let the write go ahead
end;
$$;

-- Backend/DB only (see 014): never callable through the public API.
REVOKE EXECUTE ON FUNCTION public.limita_richieste_in_attesa() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS limita_richieste_in_attesa ON public.conversazioni;
CREATE TRIGGER limita_richieste_in_attesa
  BEFORE INSERT OR UPDATE OF stato_richiesta ON public.conversazioni
  FOR EACH ROW
  EXECUTE FUNCTION public.limita_richieste_in_attesa();

-- ===================== 2. UNIQUE WAITLIST POSITION =====================

-- The sequence must never hand out a number already in use.
SELECT setval(
  pg_get_serial_sequence('public.utenti', 'posizione'),
  GREATEST(
    1, -- setval refuses 0 (empty table, unused sequence)
    (SELECT COALESCE(MAX(posizione), 0) FROM public.utenti),
    (SELECT last_value FROM pg_sequences
      WHERE schemaname || '.' || sequencename = pg_get_serial_sequence('public.utenti', 'posizione'))
  )
);

-- Fails (and the whole file with it) if duplicates exist: fix them first.
CREATE UNIQUE INDEX IF NOT EXISTS utenti_posizione_uniq ON public.utenti (posizione);
