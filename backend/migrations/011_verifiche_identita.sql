-- 011_verifiche_identita.sql
--
-- SCHEMA migration: identity verification ("Verifica identità", phase 0).
--
-- One row per attempt. The user photographs the front and back of an ID
-- document and records a short video following a random challenge (a code to
-- say out loud and two gestures), then a Roomly reviewer (utenti.admin)
-- approves or rejects it from /admin/verifiche. A user counts as verified
-- while they have an approved row: the "Identità verificata" badge reads it.
--
--   stato  bozza      started, files still being uploaded
--          in_attesa  sent, waiting for a reviewer
--          approvata  reviewer confirmed the identity
--          rifiutata  reviewer rejected it (motivo_rifiuto says why)
--
-- Every decision is also a training label for the Roomly verification model,
-- but only for users who ticked consenso_addestramento. For everyone else the
-- backend deletes the files a few days after the decision
-- (VERIFICATION_FILE_RETENTION_DAYS) and keeps only the outcome.
--
-- Same access model as 008/010: RLS on with no policies. Only the backend
-- (service role) reads and writes this table and the bucket.
--
-- Additive only, safe to run more than once. Run it BEFORE deploying the
-- backend that reads this table.

CREATE TABLE IF NOT EXISTS public.verifiche_identita (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  utente_id uuid NOT NULL REFERENCES public.utenti(id) ON DELETE CASCADE,
  stato text NOT NULL DEFAULT 'bozza'
    CHECK (stato IN ('bozza', 'in_attesa', 'approvata', 'rifiutata')),
  tipo_documento text NOT NULL
    CHECK (tipo_documento IN ('carta_identita', 'passaporto', 'patente', 'permesso_soggiorno')),
  -- The challenge shown in the video step, generated by the backend.
  codice_sfida varchar(8) NOT NULL,
  gesti_sfida text[] NOT NULL,
  consenso_verifica_at timestamptz NOT NULL,
  consenso_addestramento boolean NOT NULL DEFAULT false,
  -- Paths inside the verifiche_identita bucket; null once deleted.
  documento_fronte text,
  documento_retro text,
  video text,
  inviata_at timestamptz,
  decisa_at timestamptz,
  revisore_id uuid REFERENCES public.utenti(id) ON DELETE SET NULL,
  motivo_rifiuto text
    CHECK (motivo_rifiuto IS NULL OR motivo_rifiuto IN
      ('document_unreadable', 'document_expired', 'name_mismatch', 'face_mismatch', 'challenge_not_done', 'other')),
  nota_revisore varchar(500),
  file_eliminati_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS verifiche_identita_utente_id_idx ON public.verifiche_identita (utente_id);
CREATE INDEX IF NOT EXISTS verifiche_identita_stato_idx ON public.verifiche_identita (stato, inviata_at);

-- At most one open attempt (being filled in or waiting for review) per user.
CREATE UNIQUE INDEX IF NOT EXISTS verifiche_identita_aperta_key
  ON public.verifiche_identita (utente_id)
  WHERE stato IN ('bozza', 'in_attesa');

ALTER TABLE public.verifiche_identita ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.verifiche_identita FROM anon, authenticated;

-- Document photos and challenge videos: private, read only through
-- short-lived signed URLs made by the backend for reviewers. Files live at
-- <user id>/<verification id>/(fronte.jpg | retro.jpg | video.<webm|mp4|mov>).
